    func testWindowStatusCalculation() throws {
        let event = WarrantyEvent(vehicleID: UUID())
        let scheduled = Calendar.current.date(from: DateComponents(year: 2026, month: 6, day: 15))!
        event.scheduledDate = scheduled
        event.daysBefore = 60
        event.daysAfter = 30

        let farBefore = Calendar.current.date(byAdding: .day, value: -61, to: scheduled)!
        XCTAssertEqual(WarrantySupport.status(for: event, now: farBefore), .upcoming)

        let inWindow = Calendar.current.date(byAdding: .day, value: -30, to: scheduled)!
        XCTAssertEqual(WarrantySupport.status(for: event, now: inWindow), .inWindow)

        let overdue = Calendar.current.date(byAdding: .day, value: 31, to: scheduled)!
        XCTAssertEqual(WarrantySupport.status(for: event, now: overdue), .overdue)

        event.completedDate = scheduled
        XCTAssertEqual(WarrantySupport.status(for: event, now: overdue), .completed)
    }

    func testYearNumberDerivedFromDueDateVersusPurchase() {
